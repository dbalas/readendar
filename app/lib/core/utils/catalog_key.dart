/// Folds catalog strings so Open Library / Goodreads / localized
/// labels share a key.
String normalizeCatalogKey(String value) {
  final folded = _foldDiacritics(value.trim().toLowerCase());
  return folded
      .replaceAll(RegExp(r'[^\p{L}\p{N}\s]+', unicode: true), ' ')
      .replaceAll(RegExp(r'\s+'), ' ')
      .trim();
}

String _foldDiacritics(String input) {
  final out = StringBuffer();
  for (final rune in input.runes) {
    out.write(_diacriticFold[rune] ?? String.fromCharCode(rune));
  }
  return out
      .toString()
      .replaceAll('æ', 'ae')
      .replaceAll('œ', 'oe')
      .replaceAll('ß', 'ss');
}

