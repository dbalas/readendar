/// Resolves catalogue language values to a localized display name.
///
/// Open Library, BNE, and Wikidata return a mix of ISO-639-1, ISO-639-2, and written
/// language names. Unknown values stay visible verbatim instead of being
/// replaced with a potentially incorrect translation.
String bookLanguageDisplayName(AppL10n l, String value) {
  final trimmed = value.trim();
  if (trimmed.isEmpty) return trimmed;
  final languageCode = canonicalBookLanguageCode(trimmed);
  return languageCode == null ? trimmed : l.bookLanguageName(languageCode);
}

/// Maps a catalog/user language string onto a [bookLanguageCodes] id.
String? canonicalBookLanguageCode(String value) {
  final trimmed = value.trim();
  if (trimmed.isEmpty) return null;
  final key = normalizeCatalogKey(trimmed);
  if (key.isEmpty) return null;
  final exact = _languageAliases[key];
  if (exact != null) return exact;

  // Some sources expose a BCP-47 tag (for example `en-GB`) rather than a bare
  // language. The detail field describes the language, so the base tag is the
  // appropriate localized name.
  final base = key.split(RegExp(r'[-_\s]')).first;
  return _languageAliases[base];
}

/// ISO 639-1 code persisted for a known language, otherwise the trimmed
/// original. Empty input yields null so the field stays unset.
String? canonicalBookLanguageStorage(String value) {
  final trimmed = value.trim();
  if (trimmed.isEmpty) return null;
  return canonicalBookLanguageCode(trimmed) ?? trimmed;
}

List<String> bookLanguageCodesSorted(AppL10n l) {
  final codes = List<String>.of(bookLanguageCodes);
  codes.sort(
    (a, b) => compareLocale(
      bookLanguageDisplayName(l, a),
      bookLanguageDisplayName(l, b),
    ),
  );
  return codes;
}

